import type { AiStatus, Explanation } from '@silentfail/shared';
import type { ExplainContext } from '../explain.js';

export interface AiExplainer {
  status(): AiStatus;
  /**
   * Returns an AI-written explanation, or null when AI is disabled/unavailable/slow.
   * Callers MUST have a deterministic explanation ready either way.
   */
  explain(context: ExplainContext, deterministic: Explanation): Promise<Explanation | null>;
}

export interface AiConfig {
  enabled: boolean;
  apiKey: string | null;
  baseUrl: string;
  model: string;
  timeoutMs: number;
}

/** Reads AI configuration from the environment. Secrets never reach the client. */
export function readAiConfig(env: NodeJS.ProcessEnv = process.env): AiConfig {
  const apiKey = env['SILENTFAIL_AI_API_KEY']?.trim() || null;
  const explicit = env['SILENTFAIL_AI_ENABLED']?.trim().toLowerCase();
  const enabled = explicit === 'false' ? false : Boolean(apiKey);
  return {
    enabled,
    apiKey,
    baseUrl: (env['SILENTFAIL_AI_BASE_URL']?.trim() || 'https://api.openai.com/v1').replace(/\/$/, ''),
    model: env['SILENTFAIL_AI_MODEL']?.trim() || 'gpt-4o-mini',
    timeoutMs: Number(env['SILENTFAIL_AI_TIMEOUT_MS'] ?? 15000),
  };
}

const SYSTEM_PROMPT = [
  'You explain mutation testing results to a developer.',
  'You are given a mutation that a deterministic engine already executed, plus its measured status.',
  'Never contradict the measured status, the score or the severity: they are facts from real test execution.',
  'Explain, in plain language, why the test suite did not notice the change and what test case is missing.',
  'Reply with JSON only: {"summary": string, "detail": string, "impact": string}.',
  'summary: max 120 characters. detail: 2-4 sentences. impact: 1-2 sentences.',
].join(' ');

/**
 * Optional AI layer.
 *
 * SILENTFAIL is fully usable without it: with no API key configured, `explain`
 * short-circuits to null and the deterministic explanation is shown, labelled as
 * such in the UI. AI is a presentation aid, never a source of truth.
 */
export class OpenAiCompatibleExplainer implements AiExplainer {
  private readonly config: AiConfig;
  private lastError: string | null = null;

  constructor(config: AiConfig = readAiConfig()) {
    this.config = config;
  }

  status(): AiStatus {
    const configured = Boolean(this.config.apiKey);
    return {
      enabled: this.config.enabled && configured,
      configured,
      provider: configured ? this.config.baseUrl : null,
      model: configured ? this.config.model : null,
      detail: !configured
        ? 'No AI provider configured. All explanations are generated by the deterministic engine from real execution data.'
        : !this.config.enabled
          ? 'AI provider configured but disabled via SILENTFAIL_AI_ENABLED=false. Deterministic explanations are in use.'
          : this.lastError
            ? `AI enabled, last call failed: ${this.lastError}. Deterministic explanations are used as fallback.`
            : 'AI enabled for explanation text only. Statuses, scores and severities always come from real test execution.',
    };
  }

  async explain(context: ExplainContext, deterministic: Explanation): Promise<Explanation | null> {
    if (!this.config.enabled || !this.config.apiKey) return null;
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), this.config.timeoutMs);
    try {
      const response = await fetch(`${this.config.baseUrl}/chat/completions`, {
        method: 'POST',
        headers: {
          'content-type': 'application/json',
          authorization: `Bearer ${this.config.apiKey}`,
        },
        body: JSON.stringify({
          model: this.config.model,
          temperature: 0,
          response_format: { type: 'json_object' },
          messages: [
            { role: 'system', content: SYSTEM_PROMPT },
            { role: 'user', content: buildUserPrompt(context, deterministic) },
          ],
        }),
        signal: controller.signal,
      });
      if (!response.ok) {
        this.lastError = `HTTP ${response.status}`;
        return null;
      }
      const body = (await response.json()) as { choices?: Array<{ message?: { content?: string } }> };
      const content = body.choices?.[0]?.message?.content;
      if (!content) {
        this.lastError = 'empty response';
        return null;
      }
      const parsed = JSON.parse(content) as { summary?: string; detail?: string; impact?: string };
      if (!parsed.summary || !parsed.detail) {
        this.lastError = 'malformed response';
        return null;
      }
      this.lastError = null;
      return {
        summary: parsed.summary.slice(0, 200),
        detail: parsed.detail.slice(0, 1200),
        impact: (parsed.impact ?? deterministic.impact).slice(0, 600),
        source: 'ai',
        // Confidence stays deterministic: it is derived from execution evidence.
        confidence: deterministic.confidence,
        model: this.config.model,
      };
    } catch (error) {
      this.lastError = error instanceof Error ? error.message : String(error);
      return null;
    } finally {
      clearTimeout(timer);
    }
  }
}

function buildUserPrompt(context: ExplainContext, deterministic: Explanation): string {
  const { mutation, status, covered, killedBy, killingInput, expectedValue } = context;
  return JSON.stringify({
    file: mutation.file,
    line: mutation.line,
    function: mutation.functionName,
    operator: mutation.operator,
    originalLine: mutation.originalLine,
    mutatedLine: mutation.mutatedLine,
    measuredStatus: status,
    statementExecutedByTests: covered,
    killedByTests: killedBy,
    killingInputFoundByEngine: killingInput,
    expectedValueFromOriginalCode: expectedValue,
    deterministicSummary: deterministic.summary,
  });
}

/** Explainer used when no AI is configured: keeps the pipeline branch-free. */
export class NullAiExplainer implements AiExplainer {
  status(): AiStatus {
    return {
      enabled: false,
      configured: false,
      provider: null,
      model: null,
      detail: 'AI explanations are disabled for this run. Every explanation comes from the deterministic engine.',
    };
  }
  async explain(): Promise<Explanation | null> {
    return null;
  }
}
